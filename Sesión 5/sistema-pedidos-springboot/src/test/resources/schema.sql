CREATE TABLE pedido (
                        id BIGINT PRIMARY KEY,
                        revisado BOOLEAN NOT NULL DEFAULT FALSE,
                        estado VARCHAR(30) NOT NULL
);

CREATE TABLE pedido_revision (
                                 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 pedido_id BIGINT NOT NULL,
                                 observacion VARCHAR(500) NOT NULL,
                                 fecha_revision TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                 CONSTRAINT uq_pedido_revision UNIQUE (pedido_id),

                                 CONSTRAINT fk_revision_pedido
                                     FOREIGN KEY (pedido_id)
                                         REFERENCES pedido(id),

    -- Restricción exclusiva para provocar el fallo controlado
    -- durante la prueba de rollback.
                                 CONSTRAINT chk_observacion_prueba
                                     CHECK (observacion <> 'FORZAR_ERROR')
);
